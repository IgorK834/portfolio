// Measures the wireframe "screenshot stand-ins" in the rendered design references and writes their
// exact geometry to src/components/projects/wireframes.ts, so the site can draw them as scalable SVG.
//   node scripts/design-reference.mjs && node scripts/extract-wireframes.mjs
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

// reference page -> viewport width, and the names of its .shot elements in document order
const PAGES = {
  'home-desktop': { width: 1440, shots: ['home-workspace-wide', 'home-map-wide', 'home-builder-wide'] },
  'home-mobile': { width: 390, shots: ['home-workspace-narrow', 'home-map-narrow', 'home-builder-narrow'] },
  'case-desktop': { width: 1440, shots: ['case-hero-wide', 'case-main-wide', 'case-citations-wide', 'case-analysis-wide'] },
  'case-mobile': { width: 390, shots: ['case-hero-narrow', 'case-main-narrow', 'case-citations-narrow', 'case-analysis-narrow'] },
};

const result = {};
const browser = await chromium.launch();
for (const [page, { width, shots }] of Object.entries(PAGES)) {
  const context = await browser.newContext({ viewport: { width, height: 900 } });
  const tab = await context.newPage();
  await tab.goto(pathToFileURL(resolve(`design/reference/${page}.html`)).href, { waitUntil: 'networkidle' });
  await tab.addStyleTag({ content: '.shot .in{transform:none!important;transition:none!important}*{transition:none!important}' });
  await tab.waitForTimeout(150);
  const measured = await tab.evaluate(() => {
    const round = (n) => Math.round(n * 2) / 2;
    return [...document.querySelectorAll('.shot')].map((shot) => {
      const box = shot.getBoundingClientRect();
      const rects = [];
      shot.querySelectorAll('.in *').forEach((el) => {
        const r = el.getBoundingClientRect();
        if (r.width < 1 || r.height < 1) return;
        const bg = getComputedStyle(el).backgroundColor;
        let kind = null;
        if (el.classList.contains('b')) kind = 'b';
        else if (el.classList.contains('h')) kind = 'h';
        else if (bg === 'rgb(255, 255, 255)') kind = 'p'; // white panel with a hairline border
        if (kind) rects.push([kind, round(r.left - box.left - 1), round(r.top - box.top - 1), round(r.width), round(r.height)]);
      });
      return { w: Math.round(box.width) - 2, h: Math.round(box.height) - 2, rects };
    });
  });
  if (measured.length !== shots.length) throw new Error(`${page}: expected ${shots.length} shots, found ${measured.length}`);
  shots.forEach((name, i) => (result[name] = measured[i]));
  await context.close();
}
await browser.close();

const lines = Object.entries(result).map(
  ([name, s]) => `  '${name}': { w: ${s.w}, h: ${s.h}, rects: ${JSON.stringify(s.rects)} },`,
);
writeFileSync(
  'src/components/projects/wireframes.ts',
  `// GENERATED by scripts/extract-wireframes.mjs from the approved design. Do not edit by hand.
// Geometry of the wireframe stand-ins for project screenshots, in the design's own pixels.
// kind: b = block, h = highlighted block (takes the project accent on hover), p = white panel.
export type WireRect = ['b' | 'h' | 'p', number, number, number, number];
export interface Wireframe {
  w: number;
  h: number;
  rects: WireRect[];
}

export const wireframes: Record<string, Wireframe> = {
${lines.join('\n')}
};
`,
);
console.log(Object.entries(result).map(([n, s]) => `${n}: ${s.w}x${s.h}, ${s.rects.length} rects`).join('\n'));
